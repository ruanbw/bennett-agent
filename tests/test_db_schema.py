"""数据库结构的守门：迁移是唯一入口，且能真的走完上下行。

## 为什么这些用例比业务用例更值得写

迁移的失败方式是**部署时才炸**：本地库是老的、CI 是新建的、生产是升级的，三者结构
一旦分叉，症状是运行期随机 `UndefinedColumn`。而这类问题没有任何业务用例覆盖得到。

这里锁住四件事：

1. 库里的 revision 必须是 head（应用启动会做同样的检查）；
2. revision 落后时**必须拒绝启动**，而不是带病运行；
3. 迁移在空库上能一路升到 head，也能干净地降回 base（`downgrade` 不是摆设——
   它经常是最先腐烂的那部分代码）；
4. 代码里的模型与迁移之间**没有漂移**（等价于 CI 里的 `alembic check`）。

第 3 条用自己的临时库，避免把共享测试库降级/重建，把并行运行的其他用例打翻。
"""

from __future__ import annotations

import asyncio
import re

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from app.config import settings
from app.db import PROJECT_ROOT, current_revision, expected_head_revision, verify_schema_at_head

_SCRATCH_DB = "bennett_test_migration_roundtrip"
_SAFE_IDENTIFIER = re.compile(r"^[A-Za-z0-9_]+$")


def _config() -> Config:
    return Config(str(PROJECT_ROOT / "alembic.ini"))


async def _scratch_database(action: str) -> None:
    """在 postgres 维护库上建/删临时库。"""
    import asyncpg
    from sqlalchemy.engine import make_url

    if not _SAFE_IDENTIFIER.match(_SCRATCH_DB):
        raise AssertionError("临时库名必须通过白名单校验")

    url = make_url(settings.database_url)
    connection = await asyncpg.connect(
        host=url.host or "127.0.0.1",
        port=url.port or 5432,
        user=url.username,
        password=url.password,
        database="postgres",
    )
    try:
        if action == "create":
            await connection.execute(f'DROP DATABASE IF EXISTS "{_SCRATCH_DB}"')
            await connection.execute(f'CREATE DATABASE "{_SCRATCH_DB}"')
        else:
            await connection.execute(f'DROP DATABASE IF EXISTS "{_SCRATCH_DB}"')
    finally:
        await connection.close()


def _scratch_url() -> str:
    from sqlalchemy.engine import make_url

    return make_url(settings.database_url).set(database=_SCRATCH_DB).render_as_string(hide_password=False)


def test_database_is_at_head():
    """共享测试库由 conftest 迁移过，启动自检必须通过。"""
    assert expected_head_revision()
    assert asyncio.run(current_revision()) == expected_head_revision()
    asyncio.run(verify_schema_at_head())


async def test_stale_revision_is_refused(monkeypatch):
    """revision 不匹配时必须抛错（而不是只警告）。

    模拟「代码已升级、部署忘了跑迁移」：把版本表改成一个不存在的 revision，
    再让启动自检跑一次。测试结束后恢复，避免污染后续用例。
    """
    from sqlalchemy import text

    from app.db import engine

    head = expected_head_revision()
    stale = "0" * 12
    async with engine.begin() as connection:
        await connection.execute(text("UPDATE alembic_version SET version_num = :v"), {"v": stale})
    try:
        with pytest.raises(RuntimeError, match="不是最新"):
            await verify_schema_at_head()
    finally:
        async with engine.begin() as connection:
            await connection.execute(text("UPDATE alembic_version SET version_num = :v"), {"v": head})


def test_migrations_roundtrip_on_empty_database(monkeypatch):
    """空库 → head → base → head，全程不报错。

    用一个临时库而不是共享测试库：降级会删表，跑在共享库上会让同进程的其他用例
    （以及任何并行执行的测试）当场失败。
    """
    asyncio.run(_scratch_database("create"))
    original_url = settings.database_url
    monkeypatch.setattr(settings, "database_url", _scratch_url())
    try:
        config = _config()
        command.upgrade(config, "head")
        command.downgrade(config, "base")
        command.upgrade(config, "head")
    finally:
        monkeypatch.setattr(settings, "database_url", original_url)
        asyncio.run(_scratch_database("drop"))


def test_models_and_migrations_do_not_drift():
    """模型与迁移必须一致（等价于 `alembic check`）。

    漂移的典型形态：给模型加了一列却忘了写迁移。没有这条检查时，它只会在某个
    从未被测试覆盖的查询路径上报 `UndefinedColumn`。
    """
    try:
        command.check(_config())
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - 失败时才走
        raise AssertionError(f"模型与迁移存在漂移，请补一个 revision：{exc}") from exc
